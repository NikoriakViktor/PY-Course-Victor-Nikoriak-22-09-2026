def in_range(start, end, step=1):
    if (end-start)*step < 0:
        return None
    current = start
    dist = abs(end-start)
    while dist > 0:
        yield current
        current += step
        dist -= abs(step)

#У функції in_range(start, end, step=1) є умова current < end
#У випадку нижчек 10 > 0, що не відповідає умові, тому і список не сформувався
#Можна виправити даний недолік, змінивши умову

#Очікуваний результат: [10, 7, 4, 1]
#Отриманий результат: []
l = [i for i in in_range(10, 0, -3)]
print(l)

#Очікуваний результат: [10, 7, 4, 1]
#Отриманий результат: [10, 7, 4, 1]
l = [i for i in range(10, 0, -3)]
print(l)

#Список створився, хоча логіка поламана. Створився список [5, 6, 7, 8],
#тому що у даному випадку умова у функції in_range працює з абсолютними величинами, в даному випадку дистанцією від start до end
#Але по логіці, такий ренж не має створювати список. Це можна виправити, додавши додаткову умову. Якщо різниця між end і start
#і step мають різні знаки, то повертаємо нічого

#Очікуваний результат: [5, 4, 3, 2]
#Отриманий результат: [5, 6, 7, 8]
